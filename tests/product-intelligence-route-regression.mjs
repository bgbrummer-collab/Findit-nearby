import fs from 'node:fs';
const cfg=JSON.parse(fs.readFileSync(new URL('../vercel.json',import.meta.url),'utf8'));
const routes=Array.isArray(cfg.routes)?cfg.routes:[];
const intelligence=routes.find(r=>r?.src==='/api/product-intelligence');
if(!intelligence)throw new Error('Missing /api/product-intelligence route');
if(intelligence.dest!=='/api/product-intelligence-v2')throw new Error(`Unexpected product intelligence destination: ${intelligence.dest}`);
if(!fs.existsSync(new URL('../api/product-insights.js',import.meta.url)))throw new Error('Missing dedicated /api/product-insights function');
const stale=routes.find(r=>r?.src==='/api/product-insights');
if(stale)throw new Error(`Product insights must be served by its dedicated filesystem function, not rewritten to ${stale.dest||'another route'}`);
if(!routes.some(r=>r?.handle==='filesystem'))throw new Error('Missing filesystem route required for product insights function');
console.log('PRODUCT_INTELLIGENCE_ROUTE_REGRESSION_PASS');